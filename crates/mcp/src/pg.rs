// Postgres: the news / RAG store and unified memory.
//
// Sections:
//   1. pool    — connection pool built once in the composition root
//   2. migrate — a byte-compatible port of drizzle-orm's pg migrator
//   3. vectors — pgvector values as text literals
//   4. query   — a tiny builder for statements with optional filters
//
// The migrator matters most. The TS server migrated this database with
// drizzle, which records each applied file in `drizzle.__drizzle_migrations`
// keyed by the journal's `when` timestamp. Reading and writing that same
// table, with the same hashes, is what let this server take over the
// database at the switch-over without re-running DDL.

use deadpool_postgres::{Manager, ManagerConfig, Pool, RecyclingMethod};
use sha2::{Digest, Sha256};
use tokio_postgres::NoTls;

// ── 1. pool ──────────────────────────────────────────────────────────────────

pub type PgPool = Pool;

pub fn connect(database_url: &str) -> anyhow::Result<PgPool> {
    connect_config(database_url.parse()?)
}

pub fn connect_config(config: tokio_postgres::Config) -> anyhow::Result<PgPool> {
    let manager = Manager::from_config(config, NoTls, ManagerConfig { recycling_method: RecyclingMethod::Fast });
    Ok(Pool::builder(manager).max_size(10).build()?)
}

// Session-level advisory lock around `f`'s critical section, held on one
// pooled connection: `mcp` and `mcp-tunnel` boot against one cluster at the
// same moment, and unserialised they would race through the same DDL.
pub async fn lock(client: &deadpool_postgres::Object, key: i64) -> anyhow::Result<()> {
    client.execute("SELECT pg_advisory_lock($1)", &[&key]).await?;
    Ok(())
}

pub async fn unlock(client: &deadpool_postgres::Object, key: i64) -> anyhow::Result<()> {
    client.execute("SELECT pg_advisory_unlock($1)", &[&key]).await?;
    Ok(())
}

pub fn database_url() -> anyhow::Result<String> {
    std::env::var("DATABASE_URL").ok().filter(|v| !v.is_empty()).ok_or_else(|| {
        anyhow::anyhow!(
            "DATABASE_URL is not set. The mcp container needs Postgres for the news/RAG store; see .env.postgres.example."
        )
    })
}

// ── 2. migrate ───────────────────────────────────────────────────────────────

struct Migration {
    // Journal `when` (ms) — drizzle's ordering key and the stored created_at.
    when: i64,
    sql: &'static str,
}

// drizzle's journal (`when` per file), in order. The first four files were
// generated by drizzle-kit and must stay byte-identical: their sha256 is the
// hash already stored in production. A new migration is a new numbered file
// here with a `when` greater than the last.
const MIGRATIONS: &[Migration] = &[
    Migration { when: 1780238110688, sql: include_str!("../migrations/pg/0000_init_news.sql") },
    Migration { when: 1780326897486, sql: include_str!("../migrations/pg/0001_fancy_omega_red.sql") },
    Migration { when: 1781001341744, sql: include_str!("../migrations/pg/0002_wooden_anthem.sql") },
    Migration { when: 1787496077308, sql: include_str!("../migrations/pg/0003_lazy_puppet_master.sql") },
    Migration { when: 1790957842163, sql: include_str!("../migrations/pg/0004_news_chronological_indexes.sql") },
    Migration { when: 1791823358054, sql: include_str!("../migrations/pg/0005_memory_journal.sql") },
    Migration { when: 1791902517698, sql: include_str!("../migrations/pg/0006_memory_journal_metadata.sql") },
    Migration { when: 1791974288634, sql: include_str!("../migrations/pg/0007_news_embedding_hnsw.sql") },
    Migration { when: 1792411200004, sql: include_str!("../migrations/pg/0008_memory_doc_searchable.sql") },
];

const BREAKPOINT: &str = "--> statement-breakpoint";

// The second instance waits on the lock, then finds nothing left to apply.
const MIGRATION_LOCK: i64 = 0x006d_6370_5f6d_6967; // "mcp_mig"

pub async fn migrate(pool: &PgPool) -> anyhow::Result<()> {
    let mut client = pool.get().await?;
    lock(&client, MIGRATION_LOCK).await?;
    let result = migrate_locked(&mut client).await;
    unlock(&client, MIGRATION_LOCK).await?;
    result
}

async fn migrate_locked(client: &mut deadpool_postgres::Object) -> anyhow::Result<()> {
    // Outside the migration files so they never assume CREATE EXTENSION rights.
    client.batch_execute("CREATE EXTENSION IF NOT EXISTS vector").await?;
    client
        .batch_execute(
            r#"CREATE SCHEMA IF NOT EXISTS "drizzle";
               CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (
                 id SERIAL PRIMARY KEY,
                 hash text NOT NULL,
                 created_at bigint
               )"#,
        )
        .await?;
    let last: Option<i64> = client
        .query_opt(r#"SELECT created_at FROM "drizzle"."__drizzle_migrations" ORDER BY created_at DESC LIMIT 1"#, &[])
        .await?
        .and_then(|row| row.get(0));

    let tx = client.transaction().await?;
    let mut applied = 0;
    for migration in MIGRATIONS.iter().filter(|m| last.is_none_or(|last| last < m.when)) {
        for statement in migration.sql.split(BREAKPOINT) {
            if !statement.trim().is_empty() {
                tx.batch_execute(statement).await?;
            }
        }
        let hash = hex::encode(Sha256::digest(migration.sql.as_bytes()));
        tx.execute(
            r#"INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ($1, $2)"#,
            &[&hash, &migration.when],
        )
        .await?;
        applied += 1;
    }
    tx.commit().await?;
    tracing::info!(applied, "pg migrations applied, store ready");
    Ok(())
}

// ── 3. vectors ───────────────────────────────────────────────────────────────

// Postgres text and jsonb can't hold a NUL character: one in a value fails
// the whole statement. What pollers write without a human in the loop —
// scraped articles, mail subjects, forwarded posts — does carry them, and a
// write that fails on every retry stalls the poller behind it. Dropping the
// NUL is the closest storable text.
pub fn storable_text(text: &str) -> String {
    text.replace('\0', "")
}

// The same for a JSON value: every string in it, keys included.
pub fn storable_json(value: &serde_json::Value) -> serde_json::Value {
    use serde_json::Value;
    match value {
        Value::String(s) => Value::String(storable_text(s)),
        Value::Array(items) => Value::Array(items.iter().map(storable_json).collect()),
        Value::Object(map) => Value::Object(map.iter().map(|(k, v)| (storable_text(k), storable_json(v))).collect()),
        other => other.clone(),
    }
}

// pgvector accepts and prints `[1,2,3]`; passing it as text with a `::vector`
// cast keeps the driver free of a pgvector-specific type binding.
pub fn vector_literal(v: &[f32]) -> String {
    let mut out = String::with_capacity(v.len() * 12 + 2);
    out.push('[');
    for (i, x) in v.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        out.push_str(&x.to_string());
    }
    out.push(']');
    out
}

pub fn parse_vector(s: &str) -> Option<Vec<f32>> {
    let inner = s.trim().strip_prefix('[')?.strip_suffix(']')?;
    if inner.trim().is_empty() {
        return Some(Vec::new());
    }
    inner.split(',').map(|x| x.trim().parse().ok()).collect()
}

// ── 4. query ─────────────────────────────────────────────────────────────────

pub type Param = Box<dyn tokio_postgres::types::ToSql + Sync + Send>;

// Accumulates bind parameters for a statement whose WHERE clause depends on
// which filters the caller set. `bind` returns the `$n` placeholder.
#[derive(Default)]
pub struct Query {
    params: Vec<Param>,
}

impl Query {
    pub fn bind(&mut self, value: impl tokio_postgres::types::ToSql + Sync + Send + 'static) -> String {
        self.params.push(Box::new(value));
        format!("${}", self.params.len())
    }

    pub fn params(&self) -> Vec<&(dyn tokio_postgres::types::ToSql + Sync)> {
        self.params.iter().map(|p| p.as_ref() as &(dyn tokio_postgres::types::ToSql + Sync)).collect()
    }
}

pub fn where_clause(filters: &[String]) -> String {
    if filters.is_empty() { String::new() } else { format!("WHERE {}", filters.join(" AND ")) }
}

// Postgres-backed tests run against a throwaway database: TEST_DATABASE_URL
// when named (never prod), otherwise one pgvector container this test process
// starts on first use and Testcontainers' reaper removes when it exits. Each
// test that needs one calls `test_pool()` and returns early only when neither
// is there (no Docker) — as the TS suites do.
#[cfg(test)]
pub async fn test_pool() -> Option<PgPool> {
    let url = test_database_url()?;
    let pool = connect(&url).expect("the test database URL must parse");
    migrate(&pool).await.expect("migrations apply");
    Some(pool)
}

// A database of its own on the test server, migrated — for a test that
// needs a table nobody else writes to.
#[cfg(test)]
pub async fn fresh_test_pool() -> Option<PgPool> {
    let server = test_database_url()?;
    let name = format!("t_{:016x}", rand::random::<u64>());
    connect(&server).ok()?.get().await.ok()?.batch_execute(&format!("CREATE DATABASE {name}")).await.ok()?;
    let mut config: tokio_postgres::Config = server.parse().ok()?;
    config.dbname(&name);
    let pool = connect_config(config).ok()?;
    migrate(&pool).await.expect("migrations apply");
    Some(pool)
}

// The crate's unit tests share one database: TEST_DATABASE_URL's, or else a
// fresh one in the shared test container, made once per test process.
#[cfg(test)]
#[path = "../tests/support/container.rs"]
mod test_container;

#[cfg(test)]
pub(crate) fn test_database_url() -> Option<String> {
    if let Ok(url) = std::env::var("TEST_DATABASE_URL") {
        return Some(url);
    }
    static URL: std::sync::OnceLock<Option<String>> = std::sync::OnceLock::new();
    URL.get_or_init(|| {
        // Called from inside test runtimes, which can't be blocked on: the
        // setup gets a thread and runtime of its own.
        std::thread::spawn(|| {
            let runtime = tokio::runtime::Builder::new_current_thread().enable_all().build().ok()?;
            runtime.block_on(async {
                let server = test_container::shared_server().await.ok()?;
                let name = test_container::database_name();
                test_container::fresh_database(&server, &name).await.ok()?;
                let mut url = url::Url::parse(&server).ok()?;
                url.set_path(&format!("/{name}"));
                Some(url.to_string())
            })
        })
        .join()
        .ok()
        .flatten()
    })
    .clone()
}

